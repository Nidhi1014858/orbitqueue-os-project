#include "mem_trace.h"

#include <fstream>
#include <mutex>

namespace memtrace {

namespace {
std::ofstream g_trace_file;
std::mutex g_trace_mutex;
bool g_is_open = false;
} // namespace

const char* region_name(Region r) {
    switch (r) {
        case CODE: return "CODE";
        case MODEL_PARAMS: return "MODEL_PARAMS";
        case INPUT_BUFFER: return "INPUT_BUFFER";
        case OUTPUT_LOG: return "OUTPUT_LOG";
        case STACK: return "STACK";
    }
    return "UNKNOWN";
}

int region_first_page(Region r) {
    switch (r) {
        case CODE: return 0;
        case MODEL_PARAMS: return 2;
        case INPUT_BUFFER: return 4;
        case OUTPUT_LOG: return 6;
        case STACK: return 7;
    }
    return 0;
}

int region_num_pages(Region r) {
    switch (r) {
        case CODE: return 2;
        case MODEL_PARAMS: return 2;
        case INPUT_BUFFER: return 2;
        case OUTPUT_LOG: return 1;
        case STACK: return 1;
    }
    return 1;
}

int page_of(Region r, int offset) {
    int first = region_first_page(r);
    if (offset < 0) {
        return first;
    }
    int num = region_num_pages(r);
    int span = num * PAGE_SIZE;
    if (span <= 0) {
        return first;
    }
    return first + (offset % span) / PAGE_SIZE;
}

bool open_trace(const std::string& path) {
    std::lock_guard<std::mutex> lock(g_trace_mutex);
    if (g_is_open && g_trace_file.is_open()) {
        g_trace_file.flush();
        g_trace_file.close();
        g_is_open = false;
    }
    g_trace_file.open(path, std::ios::out | std::ios::trunc);
    if (!g_trace_file.is_open()) {
        g_is_open = false;
        return false;
    }
    g_is_open = true;
    g_trace_file << "# Logical memory access trace generated by simulated router (Exp 10 reference string)\n";
    g_trace_file.flush();
    return true;
}

void access(Region r, int offset) {
    int page = page_of(r, offset);
    std::lock_guard<std::mutex> lock(g_trace_mutex);
    if (!g_is_open || !g_trace_file.is_open()) {
        return; // Safe no-op if open_trace was not called or failed
    }
    g_trace_file << page << "\n";
}

void close_trace() {
    std::lock_guard<std::mutex> lock(g_trace_mutex);
    if (g_is_open && g_trace_file.is_open()) {
        g_trace_file.flush();
        g_trace_file.close();
    }
    g_is_open = false;
}

} // namespace memtrace
